def make_lock(label: str, pins: list[tuple[str, str]], src: str, interpreter: str = "3.14") -> str:
    """A synthetic frozen lock that satisfies every structural check."""
    head = [
        "#",
        f"# This file is autogenerated by pip-compile with Python {interpreter}",
        "# by the following command:",
        "#",
        f"#    pip-compile --allow-unsafe --generate-hashes --output-file={label} --strip-extras {src}",
        "#",
    ]
    body: list[str] = []
    for name, version in pins:
        body.append(f"{name}=={version} \\")
        body.append("    --hash=sha256:" + "a" * 64 + " \\")
        body.append("    --hash=sha256:" + "b" * 64)
        body.append(f"    # via {src}")
    return "\n".join(head + body) + "\n"


RUNTIME_PINS = [("aiohttp", "3.14.5"), ("feedparser", "6.0.14"), ("yarl", "1.25.1")]
DEV_PINS = RUNTIME_PINS + [("pip-tools", "7.5.3"), ("pip", "26.1.1"), ("ruff", "0.14.3")]


class Fixture:
    """An isolated repository-shaped fixture plus a scripted subprocess router."""

    def __init__(self, pin: str = RUNNING, workflows: str = VALID_WORKFLOW, with_workflows: bool = True):
        self.tmp = Path(tempfile.mkdtemp(prefix="ci-registry-"))
        (self.tmp / "tests").mkdir()
        (self.tmp / ".github" / "scripts").mkdir(parents=True)
        (self.tmp / "testing area").mkdir()
        (self.tmp / ".python-version").write_text(pin + "\n", encoding="utf-8")
        (self.tmp / "requirements.in").write_text("aiohttp>=3.14.3,<4\n", encoding="utf-8")
        (self.tmp / "requirements-dev.in").write_text("-r requirements.in\nruff==0.14.3\n", encoding="utf-8")
        self.runtime_lock = make_lock("requirements.txt", RUNTIME_PINS, "requirements.in")
        self.dev_lock = make_lock("requirements-dev.txt", DEV_PINS, "requirements-dev.in")
        (self.tmp / "requirements.txt").write_text(self.runtime_lock, encoding="utf-8")
        (self.tmp / "requirements-dev.txt").write_text(self.dev_lock, encoding="utf-8")
        self.wf_dir = self.tmp / ".github" / "workflows"
        if with_workflows:
            self.wf_dir.mkdir(parents=True)
            (self.wf_dir / "fixture.yml").write_text(workflows, encoding="utf-8")
        else:
            self.wf_dir.mkdir(parents=True)

        # Scripted results
        self.pip_version = "26.1.1"
        self.pip_tools_version = "7.5.3"
        self.regen_rc = 0
        self.regen_tamper: str | None = None  # e.g. "aiohttp==99.0.0"
        self.regen_identical = True
        self.install_rc = 0
        self.clean_install_rc = 0
        self.clean_install_calls: list[list[str]] = []
        self.pip_check_rc = 0
        self.regen_second_differs = False
        self._regen_calls = 0
        self.actionlint_version_rc = 0
        self.actionlint_rc = 0
        self.zizmor_version_rc = 0
        self.zizmor_rc = 0
        self.missing: set[str] = set()
        self.calls: list[list[str]] = []

    def router(self, cmd, **kwargs):
        self.calls.append(list(cmd))
        args = [str(c) for c in cmd]
        joined = " ".join(args)

        def done(rc=0, out="", err=""):
            return subprocess.CompletedProcess(args, rc, stdout=out, stderr=err)

        for tool in self.missing:
            if args and (args[0] == tool or args[-1] == tool):
                raise FileNotFoundError(2, "No such file or directory", tool)
            if tool in joined and "piptools" not in joined:
                raise FileNotFoundError(2, "No such file or directory", tool)

        if "-m" in args and "pip" in args and "--version" in args and "piptools" not in joined:
            return done(0, f"pip {self.pip_version} from /x/pip (python 3.14)\n")
        if args[0] == "pip-compile" and "--version" in args:
            if "pip-compile" in self.missing:
                raise FileNotFoundError(2, "No such file or directory", "pip-compile")
            return done(0, f"pip-compile, version {self.pip_tools_version}\n")
        if args[:3] == [args[0], "-m", "venv"] or (len(args) > 2 and args[1] == "-m" and args[2] == "venv"):
            return done(0, "created\n")
        if "install" in args and "--python" in args:
            # pip rejects --python after the subcommand, so the order is part of the contract
            self.clean_install_calls.append(args)
            if self.clean_install_rc != 0:
                return done(self.clean_install_rc, "", "ERROR: hash mismatch installing into clean venv\n")
            return done(0, "Successfully installed\n")
        if args[-1] == "check" and "pip" in args:
            if self.pip_check_rc != 0:
                return done(self.pip_check_rc, "broken requires X\n", "")
            return done(0, "No broken requirements found.\n")
        if "piptools" in args and "compile" in args:
            if self.regen_rc != 0:
                return done(self.regen_rc, "", "ERROR: could not resolve requirements\n")
            self._regen_calls += 1
            if self.regen_second_differs and self._regen_calls % 2 == 0:
                out_name2 = next((a.split("=", 1)[1] for a in args if a.startswith("--output-file=")), None)
                cwd2 = Path(kwargs.get("cwd") or self.tmp)
                seeded = (self.tmp / out_name2).read_text(encoding="utf-8")
                (cwd2 / out_name2).write_text(seeded.rstrip("\n") + "\n# drift on the second pass\n", encoding="utf-8")
                return done(0, "written\n")
            out_name = next((a.split("=", 1)[1] for a in args if a.startswith("--output-file=")), None)
            cwd = Path(kwargs.get("cwd") or self.tmp)
            assert out_name, "regeneration must name its output file"
            committed = (self.tmp / out_name).read_text(encoding="utf-8")
            if self.regen_tamper:
                name, version = self.regen_tamper.split("==")
                committed = committed.replace(f"{name}=={RUNTIME_PINS[0][1] if name == 'aiohttp' else version}",
                                              self.regen_tamper)
                committed = committed.replace("aiohttp==3.14.5", self.regen_tamper) if name == "aiohttp" else committed
            if not self.regen_identical:
                committed = committed.rstrip("\n") + "\n# unexpected trailing line\n"
            (cwd / out_name).write_text(committed, encoding="utf-8")
            return done(0, "written\n")
        if "install" in args and "--dry-run" in args:
            if self.install_rc != 0:
                return done(self.install_rc, "", "ERROR: hash mismatch for aiohttp\n")
            return done(0, "Would install aiohttp-3.14.5\n")
        if args[0] == "actionlint":
            if "-version" in args:
                return done(self.actionlint_version_rc, "1.7.7\n", "" if self.actionlint_version_rc == 0 else "broken\n")
            return done(self.actionlint_rc,
                        "" if self.actionlint_rc == 0 else "fixture.yml:12:9: shellcheck reported issue [shellcheck]\n")
        if args[0] == "zizmor":
            if "--version" in args:
                return done(self.zizmor_version_rc, "1.12.1\n", "" if self.zizmor_version_rc == 0 else "broken\n")
            return done(self.zizmor_rc, "" if self.zizmor_rc == 0 else "finding: excessive permissions\n")
        return done(0, "ok\n")

    def cleanup(self):
        import shutil

        shutil.rmtree(self.tmp, ignore_errors=True)


def run_registry(ci, fixture: Fixture, env: dict[str, str] | None = None, profile: str = "development"):
    """Run the real registry against a fixture with mocked subprocesses; return (code, out, err).

    The CI-detection environment is fully controlled here: inherited GITHUB_ACTIONS/CI are
    removed, then only the requested values are set, so each case exercises one policy path.
    """
    saved_root = ci.ROOT
    # WORKFLOW_DIR is patched when the registry exposes it; older revisions glob ROOT directly.
    has_wf_attr = hasattr(ci, "WORKFLOW_DIR")
    saved_wf = ci.WORKFLOW_DIR if has_wf_attr else None
    saved_run = subprocess.run
    inherited = {key: os.environ[key] for key in ("GITHUB_ACTIONS", "CI") if key in os.environ}
    out, err = io.StringIO(), io.StringIO()
    try:
        ci.ROOT = fixture.tmp
        if has_wf_attr:
            ci.WORKFLOW_DIR = fixture.wf_dir
        subprocess.run = fixture.router
        ci.subprocess.run = fixture.router
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            for key in inherited:
                os.environ.pop(key, None)
            os.environ.update(env or {})
            try:
                code = ci.run_profile(profile)
            finally:
                for key in (env or {}):
                    os.environ.pop(key, None)
                os.environ.update(inherited)
    finally:
        subprocess.run = saved_run
        ci.subprocess.run = saved_run
        ci.ROOT = saved_root
        if has_wf_attr:
            ci.WORKFLOW_DIR = saved_wf
    return code, out.getvalue(), err.getvalue()


